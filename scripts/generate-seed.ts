/**
 * Generates supabase/seed.sql from the typed seed modules in src/lib/seed,
 * so the database starts with exactly the content the site was designed with.
 *
 *   pnpm seed:sql
 *
 * The output is idempotent for content tables (it clears them first) and
 * never touches admins or inquiries.
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import {
  seedAbout,
  seedContact,
  seedHome,
  seedServicesHeader,
  seedSettings,
  seedWorkHeader,
} from '../src/lib/seed/site'
import { seedAlbums, seedCategories } from '../src/lib/seed/portfolio'
import { seedPackages, seedServices, seedTestimonials } from '../src/lib/seed/services'

const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`)
const j = (v: unknown) => (v == null ? 'null' : `${q(JSON.stringify(v))}::jsonb`)
const arr = (v: Array<string>) => `array[${v.map(q).join(', ')}]::text[]`
const bool = (v: boolean) => (v ? 'true' : 'false')

const out: Array<string> = [
  '-- Generated by scripts/generate-seed.ts. Do not edit by hand.',
  'begin;',
  'delete from public.media;',
  'delete from public.albums;',
  'delete from public.categories;',
  'delete from public.packages;',
  'delete from public.services;',
  'delete from public.testimonials;',
  'delete from public.page_content;',
  'delete from public.site_settings;',
  '',
]

const s = seedSettings
out.push(
  `insert into public.site_settings (id, business_name, short_name, tagline, logo, email, phones, whatsapp, location, socials, footer_note, show_packages, show_prices, show_testimonials, seo) values (1, ${q(s.businessName)}, ${q(s.shortName)}, ${q(s.tagline)}, ${j(s.logo)}, ${q(s.email)}, ${arr(s.phones)}, ${q(s.whatsapp)}, ${q(s.location)}, ${j(s.socials)}, ${q(s.footerNote)}, ${bool(s.showPackages)}, ${bool(s.showPrices)}, ${bool(s.showTestimonials)}, ${j(s.seo)});`,
  '',
)

const sections: Array<[string, string, unknown]> = [
  ['home', 'hero', seedHome.hero],
  ['home', 'intro', seedHome.intro],
  ['home', 'process', seedHome.process],
  ['home', 'showreel', seedHome.showreel],
  ['home', 'cta', seedHome.cta],
  ['about', 'main', seedAbout],
  ['contact', 'main', seedContact],
  ['work', 'header', seedWorkHeader],
  ['services', 'header', seedServicesHeader],
]
for (const [page, section, data] of sections) {
  out.push(`insert into public.page_content (page, section, data) values (${q(page)}, ${q(section)}, ${j(data)});`)
}
out.push('')

for (const c of seedCategories) {
  out.push(
    `insert into public.categories (name, slug, description, sort_order) values (${q(c.name)}, ${q(c.slug)}, ${q(c.description)}, ${c.sortOrder});`,
  )
}
out.push('')

const categorySlug = (id: string | null) => seedCategories.find((c) => c.id === id)?.slug ?? null
for (const a of seedAlbums) {
  const cat = categorySlug(a.categoryId)
  out.push(
    `insert into public.albums (slug, title, category_id, summary, story, location, shot_on, cover, published, featured, sort_order) values (${q(a.slug)}, ${q(a.title)}, ${cat ? `(select id from public.categories where slug = ${q(cat)})` : 'null'}, ${q(a.summary)}, ${q(a.story)}, ${q(a.location)}, ${a.shotOn ? `${q(a.shotOn)}::date` : 'null'}, ${j(a.cover)}, ${bool(a.published)}, ${bool(a.featured)}, ${a.sortOrder});`,
  )
  for (const m of a.media) {
    const album = `(select id from public.albums where slug = ${q(a.slug)})`
    out.push(
      m.kind === 'image'
        ? `insert into public.media (album_id, kind, image, caption, sort_order) values (${album}, 'image', ${j(m.image)}, ${q(m.caption)}, ${m.sortOrder});`
        : `insert into public.media (album_id, kind, video_url, poster, caption, sort_order) values (${album}, 'video', ${q(m.videoUrl)}, ${j(m.poster)}, ${q(m.caption)}, ${m.sortOrder});`,
    )
  }
}
out.push('')

for (const sv of seedServices) {
  out.push(
    `insert into public.services (slug, title, summary, body, cover, visible, sort_order) values (${q(sv.slug)}, ${q(sv.title)}, ${q(sv.summary)}, ${q(sv.body)}, ${j(sv.cover)}, ${bool(sv.visible)}, ${sv.sortOrder});`,
  )
}
out.push('')

const serviceSlug = (id: string | null) => seedServices.find((sv) => sv.id === id)?.slug ?? null
for (const p of seedPackages) {
  const svc = serviceSlug(p.serviceId)
  out.push(
    `insert into public.packages (service_id, name, description, price_label, features, highlighted, visible, sort_order) values (${svc ? `(select id from public.services where slug = ${q(svc)})` : 'null'}, ${q(p.name)}, ${q(p.description)}, ${q(p.priceLabel)}, ${arr(p.features)}, ${bool(p.highlighted)}, ${bool(p.visible)}, ${p.sortOrder});`,
  )
}
out.push('')

for (const t of seedTestimonials) {
  out.push(
    `insert into public.testimonials (client_name, context, quote, avatar, visible, sort_order) values (${q(t.clientName)}, ${q(t.context)}, ${q(t.quote)}, ${j(t.avatar)}, ${bool(t.visible)}, ${t.sortOrder});`,
  )
}

out.push('', 'commit;', '')

const target = resolve(import.meta.dirname, '../supabase/seed.sql')
writeFileSync(target, out.join('\n'))
console.log(`Wrote ${target}`)
